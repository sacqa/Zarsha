function makeFashionVariants(
  skuPrefix: string,
  sizes: string[],
  colors: string[],
  salePriceMinor: number,
  origPriceMinor: number,
  costMinor: number,
  image: string,
  baseStock = 18
) {
  const variants: Product['variants'] = [];
  let idx = 1;
  for (const size of sizes) {
    for (const color of colors.slice(0, 2)) {
      variants.push({
        id: `var_${skuPrefix.toLowerCase()}_${idx}`,
        sku: `${skuPrefix}-${size.replace(/\s+/g, '').toUpperCase()}-${idx}`,
        barcode: `8964001${String(1000 + idx * 17).slice(0, 6)}`,
        title: `${size} / ${color}`,
        attributes: { Size: size, Color: color },
        priceMinorUnits: salePriceMinor,
        compareAtPriceMinorUnits: origPriceMinor,
        costPerItemMinorUnits: costMinor,
        stockQuantity: Math.max(4, baseStock - (idx % 6) * 2),
        committedQuantity: 1,
        incomingQuantity: 10,
        locationStock: {
          loc_lahore_gulberg: Math.max(2, baseStock - 4),
          loc_karachi_clifton: 6,
          loc_islamabad_f7: 4,
        },
        weightGrams: 550,
        image,
      });
      idx++;
    }
  }
  return variants;
}

